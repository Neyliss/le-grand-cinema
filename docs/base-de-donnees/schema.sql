-- =====================================================================================
-- Le Grand Cinéma : base de données (PostgreSQL 16, Amazon RDS)
--
-- Ce script décrit les tables de l'application, leurs liens et leurs règles.
-- Dans le projet, les tables sont créées par Django à partir des modèles (models.py) avec
-- « python manage.py migrate » : ce script en est la version lisible, vérifiée sur PostgreSQL
-- (mêmes colonnes, mêmes types, mêmes contraintes ; voir docs/base-de-donnees/README.md).
--
-- Les cinq tables demandées : utilisateurs (auth_user), films (catalogue_film),
-- séances (catalogue_seance), réservations (reservation_reservation), places (reservation_placeseance).
-- =====================================================================================

-- ---------------------------------------------------------------- 1. UTILISATEURS
-- Table fournie par Django : personnel (agents, direction) et spectateurs qui ont un compte.
-- Le mot de passe n'est jamais stocké en clair : seulement son empreinte (algorithme PBKDF2).
CREATE TABLE auth_user (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password      varchar(128) NOT NULL,                 -- empreinte du mot de passe
    last_login    timestamptz,
    is_superuser  boolean      NOT NULL,
    username      varchar(150) NOT NULL UNIQUE,          -- l'adresse e-mail pour un spectateur
    first_name    varchar(150) NOT NULL,
    last_name     varchar(150) NOT NULL,
    email         varchar(254) NOT NULL,
    is_staff      boolean      NOT NULL,                 -- vrai pour le personnel du cinéma
    is_active     boolean      NOT NULL,
    date_joined   timestamptz  NOT NULL
);

-- Profil du spectateur (E9-US1) : adresse confirmée, accord pour recevoir les offres (E10-US1)
CREATE TABLE comptes_profil (
    id              bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id  integer NOT NULL UNIQUE REFERENCES auth_user (id) ON DELETE CASCADE,
    email_confirme  boolean NOT NULL,
    accepte_offres  boolean NOT NULL,                     -- faux par défaut (case non cochée)
    cree_le         timestamptz NOT NULL
);

-- ---------------------------------------------------------------- 2. FILMS, SALLES, TARIFS
CREATE TABLE catalogue_film (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre           varchar(120) NOT NULL,
    duree           smallint     NOT NULL CHECK (duree >= 0),          -- en minutes
    version         varchar(4)   NOT NULL,                             -- VF ou VOST
    classification  varchar(40)  NOT NULL,
    synopsis        text         NOT NULL,
    affiche         varchar(100) NOT NULL,                             -- chemin de l'image
    festival        boolean      NOT NULL                              -- film du festival de Jazz
);

CREATE TABLE catalogue_salle (
    id      bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom     varchar(40) NOT NULL UNIQUE,
    type    varchar(10) NOT NULL,
    allees  varchar(40) NOT NULL          -- numéros de sièges suivis d'une allée (dessin du plan)
);

-- Les sièges physiques d'une salle (170 dans une grande salle)
CREATE TABLE catalogue_siege (
    id       bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    salle_id bigint      NOT NULL REFERENCES catalogue_salle (id) ON DELETE CASCADE,
    rangee   varchar(2)  NOT NULL,
    numero   smallint    NOT NULL CHECK (numero >= 0),
    type     varchar(10) NOT NULL,                                    -- standard ou PMR
    CONSTRAINT siege_unique_par_salle UNIQUE (salle_id, rangee, numero)
);

-- Les tarifs sont des données, pas du code : la direction les crée dans l'administration
CREATE TABLE catalogue_tarif (
    id               bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle          varchar(60)  NOT NULL,
    prix             numeric(6,2) NOT NULL,
    actif            boolean      NOT NULL,
    ordre            smallint     NOT NULL CHECK (ordre >= 0),
    reserve_abonnes  boolean      NOT NULL                -- tarif « Abonné » (E10-US1)
);

-- ---------------------------------------------------------------- 3. SÉANCES
CREATE TABLE catalogue_seance (
    id        bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    film_id   bigint      NOT NULL REFERENCES catalogue_film (id)  ON DELETE RESTRICT,
    salle_id  bigint      NOT NULL REFERENCES catalogue_salle (id) ON DELETE RESTRICT,
    debut     timestamptz NOT NULL,
    langue    varchar(30) NOT NULL,
    statut    varchar(10) NOT NULL           -- publiee ou annulee (E5-US2)
);
CREATE INDEX seance_par_debut ON catalogue_seance (debut);   -- programmation d'un jour, rapide

-- ---------------------------------------------------------------- 4. FIDÉLITÉ (E10-US1)
CREATE TABLE fidelite_formuleabonnement (
    id         bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle    varchar(60)  NOT NULL,                     -- ex. « Carte 10 places »
    nb_places  smallint     NOT NULL CHECK (nb_places >= 0),
    prix       numeric(6,2) NOT NULL,
    actif      boolean      NOT NULL
);

CREATE TABLE fidelite_abonnement (
    id                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference         varchar(12)  NOT NULL UNIQUE,
    compte_id         integer      REFERENCES auth_user (id) ON DELETE SET NULL,   -- RGPD
    formule_id        bigint       NOT NULL REFERENCES fidelite_formuleabonnement (id) ON DELETE RESTRICT,
    prix              numeric(6,2) NOT NULL,
    places_restantes  smallint     NOT NULL CHECK (places_restantes >= 0),         -- jamais négatif
    statut            varchar(10)  NOT NULL,              -- attente ou active
    reference_stripe  varchar(255) NOT NULL,
    cree_le           timestamptz  NOT NULL,
    active_le         timestamptz
);

CREATE TABLE fidelite_offre (
    id                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre             varchar(120) NOT NULL,
    message           text         NOT NULL,
    envoyee_le        timestamptz,
    nb_destinataires  integer      NOT NULL CHECK (nb_destinataires >= 0)
);

-- ---------------------------------------------------------------- 5. RÉSERVATIONS
-- Une réservation (site ou guichet) peut se faire sans compte : compte_id est facultatif.
CREATE TABLE reservation_reservation (
    id             bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference      varchar(12)  NOT NULL UNIQUE,          -- ex. GC-7K2QM, donnée au spectateur
    jeton          varchar(40)  NOT NULL,                 -- secret du lien vers les billets
    seance_id      bigint       NOT NULL REFERENCES catalogue_seance (id) ON DELETE RESTRICT,
    compte_id      integer      REFERENCES auth_user (id) ON DELETE SET NULL,
    abonnement_id  bigint       REFERENCES fidelite_abonnement (id) ON DELETE SET NULL,
    nom            varchar(100) NOT NULL,
    email          varchar(254) NOT NULL,
    canal          varchar(10)  NOT NULL,                 -- site ou guichet
    langue         varchar(5)   NOT NULL,                 -- fr ou en : langue des e-mails
    statut         varchar(10)  NOT NULL,                 -- attente, payee ou annulee
    cree_le        timestamptz  NOT NULL,
    billets_pdf    varchar(100) NOT NULL
);

-- ---------------------------------------------------------------- 6. PLACES
-- Une ligne par siège et par séance : c'est LE stock de places, commun au site et au guichet.
CREATE TABLE reservation_placeseance (
    id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seance_id       bigint      NOT NULL REFERENCES catalogue_seance (id) ON DELETE CASCADE,
    siege_id        bigint      NOT NULL REFERENCES catalogue_siege (id)  ON DELETE RESTRICT,
    reservation_id  bigint      REFERENCES reservation_reservation (id)   ON DELETE SET NULL,
    statut          varchar(10) NOT NULL,                 -- libre, bloquee (10 minutes) ou vendue
    fin_blocage     timestamptz,
    -- La règle la plus importante : un siège n'existe qu'une fois par séance, il ne peut donc
    -- pas être vendu deux fois (même si le site et le guichet vendent au même moment).
    CONSTRAINT place_unique_par_seance UNIQUE (seance_id, siege_id)
);

-- ---------------------------------------------------------------- 7. BILLETS ET PAIEMENTS
CREATE TABLE billetterie_billet (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id    bigint       NOT NULL UNIQUE REFERENCES reservation_placeseance (id) ON DELETE CASCADE,
    tarif_id    bigint       NOT NULL REFERENCES catalogue_tarif (id) ON DELETE RESTRICT,
    prix        numeric(6,2) NOT NULL,                    -- copié à la vente : le prix ne change plus
    code_qr     varchar(32)  NOT NULL UNIQUE,             -- contenu du QR code, impossible à deviner
    utilise_le  timestamptz                               -- rempli au premier scan : refusé ensuite
);

-- Aucune donnée de carte bancaire : seulement la référence du paiement chez Stripe
CREATE TABLE paiement_paiement (
    id                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id    bigint       NOT NULL UNIQUE REFERENCES reservation_reservation (id) ON DELETE RESTRICT,
    mode              varchar(20)  NOT NULL,              -- carte en ligne, guichet, carte d'abonnement
    reference_stripe  varchar(255) NOT NULL,
    montant           numeric(8,2) NOT NULL,
    montant_recu      numeric(8,2),                       -- espèces : pour la monnaie à rendre
    statut            varchar(10)  NOT NULL,              -- reussi, echoue ou rembourse
    cree_le           timestamptz  NOT NULL
);
